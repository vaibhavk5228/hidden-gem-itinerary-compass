import { Link } from "@tanstack/react-router";
import { Clock, Heart, IndianRupee, MapPin, Sparkles } from "lucide-react";
import type { Destination } from "@/data/destinations";
import { useFavorites } from "@/hooks/use-favorites";

export function DestinationCard({ d }: { d: Destination }) {
  const fav = useFavorites();
  const saved = fav.has(d.id);
  return (
    <article className="group overflow-hidden rounded-2xl border bg-card shadow-card transition duration-300 hover:-translate-y-1 hover:shadow-lift">
      <div className="relative aspect-[4/3] overflow-hidden">
        <img src={d.image} alt={d.name} loading="lazy" width={1024} height={768} className="h-full w-full object-cover transition duration-500 group-hover:scale-105" />
        {d.hiddenGem && (
          <span className="absolute left-3 top-3 inline-flex items-center gap-1 rounded-full bg-navy/85 px-2.5 py-1 text-xs font-semibold text-navy-foreground">
            <Sparkles className="h-3 w-3 text-teal" /> Hidden gem
          </span>
        )}
        <button
          onClick={() => fav.toggle(d.id)}
          aria-label={saved ? "Remove from saved" : "Save destination"}
          className="absolute right-3 top-3 grid h-9 w-9 place-items-center rounded-full bg-card/90 transition hover:scale-110"
        >
          <Heart className={`h-4 w-4 ${saved ? "fill-destructive text-destructive" : "text-foreground"}`} />
        </button>
      </div>
      <div className="p-5">
        <div className="flex flex-wrap gap-1.5">
          {d.categories.map((c) => (
            <span key={c} className="rounded-full bg-accent px-2 py-0.5 text-[11px] font-semibold capitalize text-accent-foreground">{c}</span>
          ))}
        </div>
        <h3 className="mt-3 text-xl font-semibold">{d.name}</h3>
        <p className="mt-1 line-clamp-2 text-sm text-muted-foreground">{d.short}</p>
        <div className="mt-4 flex flex-wrap gap-x-4 gap-y-1 text-xs text-muted-foreground">
          <span className="inline-flex items-center gap-1"><MapPin className="h-3.5 w-3.5" />{d.locationHint}</span>
          <span className="inline-flex items-center gap-1"><Clock className="h-3.5 w-3.5" />~{d.estVisitMinutes} min</span>
          <span className="inline-flex items-center gap-1"><IndianRupee className="h-3.5 w-3.5" />{d.estCostINR ? `~₹${d.estCostINR}` : "Free"}</span>
        </div>
        <Link to="/destination/$id" params={{ id: d.id }} className="btn btn-navy mt-5 w-full">View details</Link>
      </div>
    </article>
  );
}

export function EmptyState({ title, text, children }: { title: string; text: string; children?: React.ReactNode }) {
  return (
    <div className="rounded-2xl border border-dashed bg-card p-10 text-center">
      <div className="mx-auto grid h-12 w-12 place-items-center rounded-full bg-accent"><MapPin className="h-5 w-5 text-accent-foreground" /></div>
      <h3 className="mt-4 text-lg font-semibold">{title}</h3>
      <p className="mt-1 text-sm text-muted-foreground">{text}</p>
      {children && <div className="mt-5">{children}</div>}
    </div>
  );
}

export function SourceBadge({ source }: { source: "ai" | "fallback" }) {
  return source === "ai" ? (
    <span className="inline-flex items-center gap-1 rounded-full bg-brand-gradient px-3 py-1 text-xs font-bold text-navy"><Sparkles className="h-3 w-3" /> Generated by Gemini AI</span>
  ) : (
    <span className="inline-flex items-center gap-1 rounded-full bg-muted px-3 py-1 text-xs font-bold text-muted-foreground">Local dataset (non-AI)</span>
  );
}

export function PageHeader({ eyebrow, title, text }: { eyebrow: string; title: string; text: string }) {
  return (
    <div className="bg-navy-gradient text-navy-foreground">
      <div className="mx-auto max-w-7xl px-4 py-14">
        <p className="text-xs font-bold uppercase tracking-[0.2em] text-teal">{eyebrow}</p>
        <h1 className="mt-2 text-4xl font-semibold md:text-5xl">{title}</h1>
        <p className="mt-3 max-w-2xl opacity-80">{text}</p>
      </div>
    </div>
  );
}
